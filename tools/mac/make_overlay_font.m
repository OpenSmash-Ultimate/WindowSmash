/* The debug overlay's glyph atlas for the macOS build: what make_overlay_font.c draws with GDI on
 * Windows (Consolas, bold, 40 pixels, white on black), drawn here with Core Text from Menlo Bold
 * (the same design as the DejaVu Sans Mono Bold the Linux build draws with), into the same C
 * header (overlay_font.h, a build product - tools/mac/build_mac.py makes it).
 *
 * Usage: make_overlay_font <output header> [font name]
 *
 * Without a font name: Menlo Bold, else the system's fixed-pitch font made bold. */
#import <CoreGraphics/CoreGraphics.h>
#import <CoreText/CoreText.h>
#import <Foundation/Foundation.h>
#include <stdio.h>
#include <string.h>

#define CELL_W 24
#define CELL_H 48
#define COLS 16
#define ATLAS_W (CELL_W * COLS)
#define ATLAS_H (CELL_H * 6)
#define SIZE 40   /* (CreateFontW(-40): a 40-pixel em) */

/* The named font, only if that is what Core Text found (it stands in another for a name it does not know). */
static CTFontRef font_named(NSString *name) {
    CTFontRef font = CTFontCreateWithName((__bridge CFStringRef)name, SIZE, NULL);
    if (!font) return NULL;
    NSString *got = CFBridgingRelease(CTFontCopyPostScriptName(font));
    if ([got caseInsensitiveCompare:name] == NSOrderedSame) return font;
    CFRelease(font);
    return NULL;
}

static CTFontRef pick_font(const char *wanted) {
    CTFontRef font = font_named(wanted ? @(wanted) : @"Menlo-Bold");
    if (font || wanted) return font;
    CTFontRef fixed = CTFontCreateUIFontForLanguage(kCTFontUIFontUserFixedPitch, SIZE, NULL);
    if (!fixed) return NULL;
    font = CTFontCreateCopyWithSymbolicTraits(fixed, SIZE, NULL, kCTFontTraitBold, kCTFontTraitBold);
    if (font) CFRelease(fixed);
    return font ? font : fixed;
}

int main(int argc, char **argv) {
    @autoreleasepool {
        if (argc < 2) {
            fprintf(stderr, "usage: make_overlay_font <output header> [font name]\n");
            return 2;
        }
        CTFontRef font = pick_font(argc > 2 ? argv[2] : NULL);
        if (!font) {
            fprintf(stderr, "no such font: %s\n", argc > 2 ? argv[2] : "Menlo-Bold");
            return 1;
        }
        static unsigned char coverage[ATLAS_W * ATLAS_H];   /* rows top to bottom, as the bitmap's memory is */
        CGColorSpaceRef gray = CGColorSpaceCreateDeviceGray();
        CGContextRef dc = CGBitmapContextCreate(coverage, ATLAS_W, ATLAS_H, 8, ATLAS_W, gray, (CGBitmapInfo)kCGImageAlphaNone);
        CGColorSpaceRelease(gray);
        if (!dc) return 1;
        CGContextSetGrayFillColor(dc, 0, 1);
        CGContextFillRect(dc, CGRectMake(0, 0, ATLAS_W, ATLAS_H));
        CGContextSetGrayFillColor(dc, 1, 1);
        CGContextSetShouldAntialias(dc, true);
        CGContextSetShouldSmoothFonts(dc, false);   /* plain coverage, as GDI's ANTIALIASED_QUALITY */
        /* Each glyph with the top of its line at (x, y + 2) of its cell, as GDI's TextOut puts it:
         * the baseline is the font's ascent below that. (User space is y up from the bottom.) */
        CGFloat ascent = CTFontGetAscent(font);
        for (int c = 32; c < 127; c++) {
            UniChar ch = (UniChar)c;
            CGGlyph glyph;
            if (!CTFontGetGlyphsForCharacters(font, &ch, &glyph, 1)) continue;
            CGFloat x = (c - 32) % COLS * CELL_W, top = (c - 32) / COLS * CELL_H + 2;
            CGPoint at = CGPointMake(x, ATLAS_H - top - ascent);
            CTFontDrawGlyphs(font, &glyph, &at, 1, dc);
        }
        CGContextFlush(dc);
        CGContextRelease(dc);
        NSString *name = CFBridgingRelease(CTFontCopyPostScriptName(font));
        CFRelease(font);
        FILE *f = fopen(argv[1], "w");
        if (!f) {
            perror(argv[1]);
            return 1;
        }
        fprintf(f, "/* Generated by tools/mac/make_overlay_font.m: %dx%d coverage, printable ASCII in %dx%d cells. */\n", ATLAS_W, ATLAS_H, CELL_W, CELL_H);
        fprintf(f, "static const unsigned char overlay_font[%d] = {\n", ATLAS_W * ATLAS_H);
        for (int i = 0; i < ATLAS_W * ATLAS_H; i++) fprintf(f, "%u,%s", (unsigned)coverage[i], i % 32 == 31 ? "\n" : "");
        fprintf(f, "};\n");
        if (fclose(f)) return 1;
        printf("wrote %s (%s)\n", argv[1], name.UTF8String);
        return 0;
    }
}
